// Prints W5TestVectors.kt. The inputs mirror W5WalletTest; change both together.
import { WalletContractV4, WalletContractV5R1 } from "@ton/ton";
import { Address, beginCell, comment, internal, storeStateInit } from "@ton/core";
import { keyPairFromSeed } from "@ton/crypto";

// Throwaway test key: seed bytes 0x01..0x20.
const keyPair = keyPairFromSeed(Buffer.from(Array.from({ length: 32 }, (_, i) => i + 1)));

const v4 = WalletContractV4.create({ workchain: 0, publicKey: keyPair.publicKey });
const w5 = WalletContractV5R1.create({ publicKey: keyPair.publicKey });
const w5Testnet = WalletContractV5R1.create({
    publicKey: keyPair.publicKey,
    walletId: { networkGlobalId: -3, context: { workchain: 0, walletVersion: "v5r1", subwalletNumber: 0 } },
});

const recipient = Address.parse("0:" + "2f".repeat(32));
const jettonWallet = Address.parse("0:" + "3c".repeat(32));
const validUntil = 1_893_456_000;
// ton-kit writes 32 one-bits instead of valid_until while deploying, as for v4R2.
const deployValidUntil = 0xffffffff;
const rawTime = 1_893_455_000;
const queryId = 12345n;

async function unsignedBody(seqno, timeout, sendMode, messages) {
    let body;
    await w5.createTransfer({
        seqno,
        timeout,
        sendMode,
        messages,
        authType: "external",
        signer: async (cell) => {
            body = cell;
            return Buffer.alloc(64);
        },
    });
    return body;
}

function jettonTransferBody() {
    return beginCell()
        .storeUint(0x0f8a7ea5, 32)
        .storeUint(queryId, 64)
        .storeCoins(1_000_000n)
        .storeAddress(recipient)
        .storeAddress(w5.address)
        .storeBit(false)
        .storeCoins(1n)
        .storeMaybeRef(comment("hi"))
        .endCell();
}

const boc = (cell) => cell.toBoc({ idx: false, crc32: false }).toString("base64");

const vectors = {
    V4R2_ADDRESS: v4.address.toRawString(),
    W5_ADDRESS: w5.address.toRawString(),
    W5_TESTNET_ADDRESS: w5Testnet.address.toRawString(),
    W5_STATE_INIT: boc(beginCell().store(storeStateInit(w5.init)).endCell()),
    W5_TON_SEQNO_0: boc(await unsignedBody(0, deployValidUntil, 3, [
        internal({ to: recipient, value: 1_000_000_000n, bounce: false, init: w5.init, body: comment("deploy") }),
    ])),
    W5_TON_SEQNO_5: boc(await unsignedBody(5, validUntil, 3, [
        internal({ to: recipient, value: 500_000_000n, bounce: false, body: comment("memo") }),
    ])),
    W5_TON_MAX: boc(await unsignedBody(5, validUntil, 128, [
        internal({ to: recipient, value: 0n, bounce: false }),
    ])),
    W5_JETTON: boc(await unsignedBody(5, validUntil, 3, [
        internal({ to: jettonWallet, value: 64_000_000n, bounce: true, body: jettonTransferBody() }),
    ])),
    W5_THREE_MESSAGES: boc(await unsignedBody(5, rawTime + 300, 3, [
        internal({ to: Address.parse("0:" + "a1".repeat(32)), value: 100_000_000n, bounce: true }),
        internal({ to: Address.parse("0:" + "b2".repeat(32)), value: 200_000_000n, bounce: false, body: comment("second") }),
        internal({ to: Address.parse("0:" + "c3".repeat(32)), value: 300_000_000n, bounce: true }),
    ])),
};

console.log("package io.horizontalsystems.tonkit.core\n");
console.log("// Generated by tools/w5-vectors (see its README); do not edit by hand.");
console.log("internal object W5TestVectors {");
for (const [name, value] of Object.entries(vectors)) {
    console.log(`    const val ${name} = "${value}"`);
}
console.log("}");
